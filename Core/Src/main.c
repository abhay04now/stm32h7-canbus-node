// This callback runs automatically whenever HAL detects a new message sitting
// in RX FIFO0 (we enabled this notification with HAL_FDCAN_ActivateNotification
// below). In loopback mode, this fires right after our own transmitted frame
// loops back into the RX path.

void HAL_FDCAN_RxFifo0Callback(FDCAN_HandleTypeDef *hfdcan, uint32_t RxFifo0ITs)
{
    if ((RxFifo0ITs & FDCAN_IT_RX_FIFO0_NEW_MESSAGE) != 0)
    {
        if (HAL_FDCAN_GetRxMessage(hfdcan,
                                   FDCAN_RX_FIFO0,
                                   &RxHeader,
                                   RxData) == HAL_OK)
        {
            printf("CAN RX: ID=0x%03lX DLC=%lu DATA=",
                   RxHeader.Identifier,
                   RxHeader.DataLength);

            for (int i = 0; i < 8; i++)
            {
                printf("%02X ", RxData[i]);
            }

            printf("\r\n");
        }
    }
}
